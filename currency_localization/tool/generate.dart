// Run from currency_localization: dart run tool/generate.dart [--check]
import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';

void main(List<String> arguments) {
  final package = File.fromUri(Platform.script).parent.parent;
  final root = package.parent;
  final currencies = jsonDecode(
    File('${root.path}/currency.json').readAsStringSync(),
  ) as Map<String, dynamic>;
  final codes = currencies.keys.toList()..sort();
  final directory = Directory('${root.path}/data/localizations');
  final locales = directory
      .listSync()
      .whereType<File>()
      .map((f) => f.uri.pathSegments.last)
      .where((f) => f.endsWith('.json'))
      .map((f) => f.substring(0, f.length - 5))
      .toList()
    ..sort();
  final parentFile = File('${root.path}/data/locale_parents.json');
  final parents = jsonDecode(parentFile.readAsStringSync()) as Map;
  String literal(String value) => jsonEncode(value).replaceAll(r'$', r'\$');
  final output = StringBuffer(
    '// GENERATED by tool/generate.dart. Do not edit.\n'
    '// Source: data/localizations and data/locale_parents.json.\n'
    'const currencyNameLocales = <String>{${locales.map((l) => literal(l.toLowerCase())).join(', ')},};\n'
    'const currencyNameCodes = <String>{${codes.map(literal).join(', ')},};\n'
    'const localizedCurrencyNames = <String, Map<String, String>>{\n',
  );
  final sources = <Map<String, Object>>[];
  for (final locale in locales) {
    final source = File('${root.path}/data/localizations/$locale.json');
    final bytes = source.readAsBytesSync();
    final decoded = jsonDecode(utf8.decode(bytes)) as Map<String, dynamic>;
    final names = decoded;
    for (final entry in names.entries) {
      if (!codes.contains(entry.key) ||
          entry.value is! String ||
          (entry.value as String).trim().isEmpty ||
          entry.value == entry.key) {
        throw FormatException(
            'Invalid compact translation: $locale/${entry.key}');
      }
    }
    final missing = <String>[];
    var count = 0;
    output.writeln('  ${literal(locale.toLowerCase())}: {');
    for (final code in codes) {
      final name = names[code];
      if (name == null || name == code) {
        missing.add(code);
        continue;
      }
      if (name is! String || name.trim().isEmpty || name == 'â†‘â†‘â†‘') {
        throw FormatException('Invalid localized name: $locale/$code');
      }
      output.writeln('    ${literal(code)}: ${literal(name)},');
      count++;
    }
    output.writeln('  },');
    sources.add({
      'locale': locale,
      'sha256': sha256.convert(bytes).toString(),
      'translatedCount': count,
      'missingCodes': missing,
    });
  }
  output.writeln('};');
  output.writeln('const currencyLocaleParents = <String, String>{');
  for (final key in (parents.keys.cast<String>().toList()..sort())) {
    output.writeln(
        '  ${literal(key.toLowerCase())}: ${literal((parents[key] as String).toLowerCase())},');
  }
  output.writeln('};');
  final target = File('${package.path}/lib/src/currency_names.dart');
  final temporary = File('${target.path}.tmp.dart');
  try {
    temporary.writeAsStringSync(output.toString());
    final formatted = Process.runSync(Platform.resolvedExecutable, [
      '--suppress-analytics',
      'format',
      temporary.path,
    ]);
    if (formatted.exitCode != 0) {
      throw StateError('Formatting failed: ${formatted.stderr}');
    }
    write(target, temporary.readAsStringSync(), arguments.contains('--check'));
  } finally {
    if (temporary.existsSync()) temporary.deleteSync();
  }
  final license = File('${package.path}/third_party/UNICODE_LICENSE.txt');
  final provenance = {
    'localeCount': locales.length,
    'sourceFormat': 'Compact ISO code to display name maps',
    'parentLocalesSha256':
        sha256.convert(parentFile.readAsBytesSync()).toString(),
    'licenseSha256': sha256.convert(license.readAsBytesSync()).toString(),
    'currencyCount': codes.length,
    'coverage':
        'Current and selected historical codes from the repository currency.json. Display names only; no plural amount forms.',
    'sources': sources,
  };
  write(
      File('${package.path}/data_coverage.json'),
      '${const JsonEncoder.withIndent('  ').convert(provenance)}\n',
      arguments.contains('--check'));
}

void write(File target, String content, bool check) {
  if (check) {
    if (!target.existsSync() || target.readAsStringSync() != content) {
      stderr.writeln('Stale ${target.path}; run dart run tool/generate.dart');
      exitCode = 1;
    }
  } else {
    target.writeAsStringSync(content);
  }
}
